pub fn translate_dynamic(s: &str) -> Option<String> {
    for (key, translated) in DYNAMIC {
        let parts: Vec<_> = key.split("{}").collect();
        if let Some(captures) = crate::i18n::match_template(&parts, s) {
            let mut out = String::new();
            for (i, piece) in translated.split("{}").enumerate() {
                out.push_str(piece);
                if let Some(capture) = captures.get(i) {
                    out.push_str(capture);
                }
            }
            return Some(out);
        }
    }
    None
}

